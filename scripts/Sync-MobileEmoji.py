"""Copy the PC emoji catalog and art to the static web app. Android uses Gradle Sync."""
import json
import shutil
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'src/Lantern.App/Assets/Emoji'
catalog = json.loads((source / 'zalo-catalog.json').read_text(encoding='utf-8-sig'))
codes = json.loads((root / 'src/Lantern.Core/emoji-shortcodes.json').read_text(encoding='utf-8-sig'))
target = root / 'pwa/assets/emoji'
target.mkdir(parents=True, exist_ok=True)
for item in catalog:
    path = target / item['File']
    path.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source / item['File'], path)
(root / 'pwa/emoji-data.js').write_text('// Generated by scripts/Sync-MobileEmoji.py.\nexport const catalog = ' + json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + ';\nexport const shortcodes = ' + json.dumps(codes, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
(root / 'pwa/emoji-precache.js').write_text('// Generated by scripts/Sync-MobileEmoji.py.\nself.LANTERN_EMOJI_FILES = ' + json.dumps(sorted({'/assets/emoji/' + item['File'] for item in catalog}), separators=(',', ':')) + ';\n', encoding='utf-8')
